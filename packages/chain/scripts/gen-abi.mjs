// Regenerates src/abi/RungsPool.ts from the Foundry artifact. Run after `forge build` in contracts/.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const art = JSON.parse(readFileSync(`${root}contracts/out/RungsPool.sol/RungsPool.json`, "utf8"));
const out = `// Generated by packages/chain/scripts/gen-abi.mjs from contracts/out/RungsPool.sol/RungsPool.json. Do not edit.\n\nexport const rungsPoolAbi = ${JSON.stringify(art.abi, null, 2)} as const;\n`;
writeFileSync(`${root}packages/chain/src/abi/RungsPool.ts`, out);
console.log(`wrote ${art.abi.length} ABI entries`);
